function localize(table: Record<string, string>, canonical: string): string {
  if (getLanguage() !== "zh") {
    return canonical;
  }
  return table[canonical] ?? canonical;
}

/** Localized display name for any English canonical content label. */
export function contentName(canonical: string): string {
  return localize(zhNames, canonical);
}

/** Localized description for upgrades/customer archetypes etc. */
export function contentDescription(canonical: string): string {
  return localize(zhDescriptions, canonical);
}
