/**
 * Canonical dictionary shape. Values are inferred as `string` (not `as const`)
 * so other locales can provide their own text while the object structure — the
 * set of keys — stays locked and is enforced on every locale file.
 */
export type Dictionary = typeof en;

export type MessageKey = DeepKeys<Dictionary>;

type DeepKeys<T> = T extends string
  ? never
  : {
      [K in keyof T & string]: T[K] extends string ? K : `${K}.${DeepKeys<T[K]>}`;
    }[keyof T & string];
